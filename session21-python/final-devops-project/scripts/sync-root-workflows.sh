#!/usr/bin/env bash
# GitHub only runs workflows from <repo-root>/.github/workflows. This project lives in a
# sub-folder of the devops-heros monorepo, so the workflows in ./.github/workflows (the
# standalone-repo version, source of truth) are copied to the repo root with:
#   - a `paths:` filter so they only run for changes to this project
#   - APP_DIR / working-directory pointing at this folder
#   - workflow names prefixed with "Session 21" so they stand out in the Actions tab
#
#   ./scripts/sync-root-workflows.sh        (run after editing ci.yml / cd.yml)
set -euo pipefail

PROJECT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO="$(git -C "$PROJECT" rev-parse --show-toplevel)"
REL="${PROJECT#"$REPO"/}"

python3 - "$PROJECT" "$REPO" "$REL" <<'PY'
import re
import sys
from pathlib import Path

project, repo, rel = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
names = {"ClinicFlow CI": "Session 21 - ClinicFlow CI", "ClinicFlow CD": "Session 21 - ClinicFlow CD (GitOps)"}

for src_name, dst_name in (("ci.yml", "session21-ci.yml"), ("cd.yml", "session21-cd.yml")):
    text = (project / ".github/workflows" / src_name).read_text()
    header = (
        f"# GENERATED by {rel}/scripts/sync-root-workflows.sh - do not edit by hand.\n"
        f"# Source of truth: {rel}/.github/workflows/{src_name}\n"
    )
    text = re.sub(r"\A(#[^\n]*\n){2}", header, text)  # replace the 2-line standalone header
    for old, new in names.items():
        text = text.replace(f'name: {old}\n', f'name: {new}\n').replace(f'["{old}"]', f'["{new}"]')
    text = text.replace("APP_DIR: .\n", f"APP_DIR: {rel}\n")
    text = text.replace("working-directory: .\n", f"working-directory: {rel}\n", 1)  # job defaults only
    filt = (
        "    paths:\n"
        f'      - "{rel}/**"\n'
        f'      - "!{rel}/**/*.md"\n'
        f'      - "!{rel}/screenshots/**"\n'
        "      # CD commits only the pinned image tag - that must not rebuild the images\n"
        f'      - "!{rel}/helm/clinicflow/values-prod.yaml"\n'
        f'      - "!{rel}/gitops/**"\n'
        f'      - ".github/workflows/{dst_name}"\n'
    )
    text = re.sub(r"    paths-ignore:\n(      - [^\n]*\n)+", filt, text)
    (repo / ".github/workflows" / dst_name).write_text(text)
    print(f"wrote .github/workflows/{dst_name}")
PY
